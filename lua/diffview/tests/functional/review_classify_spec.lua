local helpers = require("diffview.tests.helpers")
local RevType = require("diffview.vcs.rev").RevType

local eq = helpers.eq

vim.env.GIT_CONFIG_GLOBAL = "/dev/null"
vim.env.GIT_CONFIG_NOSYSTEM = "1"

local function filters(tests_extend)
  return {
    tests = { hidden = true, extend = tests_extend or {} },
    generated = { hidden = true, extend = {} },
    reviewed = { hidden = false },
  }
end

describe("diffview.review.classify", function()
  local classify = require("diffview.review.classify")

  it("tells tests, generated and code apart", function()
    local cases = {
      { "a_test.go", {}, "test" },
      { "Sources/FooTests.swift", {}, "test" },
      { "lua/x_spec.lua", {}, "test" },
      { "web/app.test.tsx", {}, "test" },
      { "pkg/testdata/in.json", {}, "test" },
      { "test_x.py", {}, "test" },
      { "go.sum", {}, "generated" },
      { "web/package-lock.json", {}, "generated" },
      { "Package.resolved", {}, "generated" },
      { "api/x.pb.go", { header = { "// Code generated by protoc. DO NOT EDIT." } }, "generated" },
      { "gen/x.go", { attrs = { generated = true } }, "generated" },
      { "a.go", { attrs = { test = true } }, "test" },
      { "mock_test.go", { attrs = { generated = true } }, "generated" },
      { "go.mod", {}, "code" },
      { "cmd/main.go", {}, "code" },
    }
    for _, c in ipairs(cases) do
      eq({ c[1], c[3] }, { c[1], classify.kind(c[1], c[2], filters()) })
    end
  end)

  it("takes extra patterns from the config", function()
    eq("test", classify.kind("ui/ui_snapshot.json", {}, filters({ "*_snapshot.json" })))
  end)

  local function entry(path)
    return { path = path, revs = { b = { type = RevType.LOCAL } } }
  end

  local function apply(toplevel, files)
    local done = false
    classify.apply({ ctx = { toplevel = toplevel } }, files, function()
      done = true
    end)
    assert(vim.wait(5000, function()
      return done
    end, 20), "apply did not finish")
  end

  it("reads the repo's .gitattributes", function()
    local repo = vim.fn.tempname()
    vim.fn.mkdir(repo .. "/gen", "p")
    vim.fn.mkdir(repo .. "/spec", "p")
    vim.fn.system({ "git", "-C", repo, "init", "-q" })
    vim.fn.writefile({ "gen/** linguist-generated", "spec/** diffview-test" }, repo .. "/.gitattributes")
    local files = { entry("gen/x.go"), entry("spec/y.go"), entry("z.go") }
    apply(repo, files)
    eq({ "generated", "test", "code" }, vim.tbl_map(function(f)
      return f.review_kind
    end, files))
  end)

  it("falls back to the built-in rules when git check-attr fails", function()
    local dir = vim.fn.tempname()
    vim.fn.mkdir(dir, "p")
    local files = { entry("a_test.go"), entry("a.go") }
    apply(dir, files)
    eq({ "test", "code" }, vim.tbl_map(function(f)
      return f.review_kind
    end, files))
  end)
end)
