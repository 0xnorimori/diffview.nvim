local helpers = require("diffview.tests.helpers")

local eq = helpers.eq
local git = helpers.git
local wait_for = helpers.wait_for

vim.env.GIT_CONFIG_GLOBAL = "/dev/null"
vim.env.GIT_CONFIG_NOSYSTEM = "1"

describe("diffview file panel review", function()
  local clubmate, repo, tab

  local function view()
    return require("diffview.lib").tabpage_to_view(tab)
  end

  local function panel()
    return view().panel
  end

  local function text()
    return table.concat(vim.api.nvim_buf_get_lines(panel().bufid, 0, -1, false), "\n")
  end

  local function listed(name)
    return text():find(" " .. name, 1, true) ~= nil
  end

  local function open()
    tab = clubmate.open({ cwd = repo, base = "HEAD" })
    wait_for(function()
      return view() and view().initialized and panel().bufid and text():find("Review", 1, true) ~= nil
    end)
  end

  before_each(function()
    vim.cmd("runtime! plugin/diffview.lua")
    require("diffview").setup({ use_icons = false })
    clubmate = require("diffview.clubmate")
    repo = helpers.make_repo()
    vim.fn.writefile({ "x h1:abc" }, repo .. "/go.sum")
  end)

  after_each(function()
    clubmate.close(tab)
  end)

  it("hides tests and generated by default", function()
    open()
    eq({ true, true, false, false, false }, {
      listed("a.go"), listed("new.txt"), listed("a_test.go"), listed("b_test.go"), listed("go.sum"),
    })
    assert.truthy(text():find("tests 2", 1, true))
    assert.truthy(text():find("gen 1", 1, true))
    assert.truthy(text():find("0/2", 1, true))
    assert.truthy(text():find("zt tests · zg gen · zr reviewed", 1, true))
  end)

  it("toggles each filter", function()
    open()
    panel():toggle_filter("tests")
    eq(true, listed("a_test.go"))
    assert.truthy(text():find("0/4", 1, true))
    panel():toggle_filter("tests")
    eq(false, listed("a_test.go"))
  end)

  it("keeps the count when reviewed files are hidden", function()
    open()
    clubmate.set_reviewed("a.go", true, tab)
    assert.truthy(text():find("1/2", 1, true))
    panel():toggle_filter("reviewed")
    eq(false, listed("a.go"))
    assert.truthy(text():find("1/2", 1, true))
  end)

  it("keeps a hidden current file open", function()
    open()
    panel():toggle_filter("tests")
    clubmate.select("a_test.go", tab)
    wait_for(function()
      return view().cur_entry and view().cur_entry.path == "a_test.go"
    end)
    panel():toggle_filter("tests")
    eq("a_test.go", view().cur_entry.path)
    eq(false, vim.tbl_contains(vim.tbl_map(function(f)
      return f.path
    end, panel():ordered_file_list()), "a_test.go"))
    eq("code", panel():next_file().review_kind)
  end)

  it("shows 0/0 when everything is hidden", function()
    repo = vim.fn.tempname()
    vim.fn.mkdir(repo, "p")
    git(repo, "init", "-q")
    vim.fn.writefile({ "package x" }, repo .. "/x_test.go")
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "init")
    vim.fn.writefile({ "package x", "func TestX() {}" }, repo .. "/x_test.go")
    open()
    assert.truthy(text():find("0/0", 1, true))
    eq(false, listed("x_test.go"))
  end)

  it("moves on to the next file after staging a directory", function()
    vim.fn.mkdir(repo .. "/d", "p")
    vim.fn.writefile({ "package d" }, repo .. "/d/x.go")
    tab = clubmate.open({ cwd = repo })
    wait_for(function()
      return view() and view().initialized and text():find("Review", 1, true) ~= nil
    end)
    clubmate.set_panel(true, tab)
    local dir
    panel().components.comp:deep_some(function(comp)
      if comp.name == "directory" and comp.context.name == "d" then
        dir = comp
        return true
      end
    end)
    vim.api.nvim_set_current_win(panel().winid)
    vim.api.nvim_win_set_cursor(panel().winid, { dir.lstart + 1, 0 })
    eq("d/x.go", panel().cur_file.path)
    require("diffview.actions").toggle_stage_entry()
    eq("a.go", panel().cur_file.path)
  end)
end)
