local helpers = require("diffview.tests.helpers")

local eq = helpers.eq
local git = helpers.git
local wait_for = helpers.wait_for

vim.env.GIT_CONFIG_GLOBAL = "/dev/null"
vim.env.GIT_CONFIG_NOSYSTEM = "1"

describe("diffview file panel review", function()
  local clubmate, repo, tab

  local function view()
    return require("diffview.lib").tabpage_to_view(tab)
  end

  local function panel()
    return view().panel
  end

  local function lines(buf)
    return vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  end

  local function text()
    return table.concat(lines(panel().bufid), "\n")
  end

  local function header()
    return table.concat(lines(panel().header_buf), "\n")
  end

  local function footer()
    return table.concat(lines(panel().footer_buf), "\n")
  end

  local function listed(name)
    return text():find(" " .. name, 1, true) ~= nil
  end

  local function row(buf, pattern)
    for i, l in ipairs(lines(buf)) do
      if l:find(pattern, 1, true) then
        return i, l
      end
    end
  end

  local function click(win, buf, pattern, needle)
    local i, l = row(buf, pattern)
    assert(i, "no line with " .. pattern)
    return panel():activate(win, i, l:find(needle or pattern, 1, true) - 1)
  end

  local function open()
    tab = clubmate.open({ cwd = repo, base = "HEAD" })
    wait_for(function()
      return view() and view().cur_entry and view().cur_entry.opened and panel().header_buf ~= nil
    end)
  end

  before_each(function()
    vim.cmd("runtime! plugin/diffview.lua")
    require("diffview").setup({ use_icons = false })
    clubmate = require("diffview.clubmate")
    repo = helpers.make_repo()
    vim.fn.writefile({ "x h1:abc" }, repo .. "/go.sum")
  end)

  after_each(function()
    clubmate.close(tab)
  end)

  it("pins a header and a footer around the file tree", function()
    open()
    local p = panel()
    eq({ p.header_win, p.winid, p.footer_win }, vim.tbl_filter(function(win)
      return vim.tbl_contains({ p.header_win, p.winid, p.footer_win }, win)
    end, vim.api.nvim_tabpage_list_wins(tab)))
    eq(#lines(p.header_buf), vim.api.nvim_win_get_height(p.header_win))
    eq(#lines(p.footer_buf), vim.api.nvim_win_get_height(p.footer_win))
    assert.truthy(header():find("0 / 2 reviewed", 1, true))
    assert.truthy(header():find("+5 −1 · no comments", 1, true))
    assert.truthy(header():find("Show ☑ code ☐ tests 2 ☐ generated 1", 1, true))
    assert.truthy(footer():find(" r  reviewed   ]f  next to review", 1, true))
    assert.truthy(footer():find(" ,rc  comment   ]a  next comment", 1, true))
    assert.truthy(footer():find("Send review ⌘↩", 1, true))
    assert.truthy(footer():find("○ to review  ✓ reviewed", 1, true))
    for _, buf in ipairs(p:buffers()) do
      vim.api.nvim_buf_call(buf, function()
        eq(1, vim.fn.maparg("<LeftRelease>", "n", false, true).buffer)
      end)
    end
    vim.api.nvim_set_current_win(view().cur_layout.b.id)
    eq(false, vim.wo[p.winid].cursorline)
    vim.api.nvim_set_current_win(p.winid)
    eq(true, vim.wo[p.winid].cursorline)
    clubmate.set_panel(false, tab)
    eq(false, vim.api.nvim_win_is_valid(p.header_win or -1))
    eq(false, vim.api.nvim_win_is_valid(p.footer_win or -1))
  end)

  it("draws one statusline under the panel, rules between its parts", function()
    vim.o.laststatus = 2
    open()
    local p = panel()
    local function status(win)
      return vim.api.nvim_eval_statusline(vim.wo[win].statusline, { winid = win }).str
    end
    local width = vim.api.nvim_win_get_width(p.winid)
    eq(string.rep("─", width), status(p.header_win))
    eq(string.rep("─", width), status(p.winid))
    eq(vim.go.statusline, vim.wo[p.footer_win].statusline)
    assert.falsy(vim.go.statusline:find("─", 1, true))
  end)

  it("draws a row per file with its state, kind chip and right-aligned counts", function()
    open()
    clubmate.set_reviewed("a.go", true, tab)
    local width = vim.api.nvim_win_get_width(panel().winid)
    local _, a = row(panel().bufid, "a.go")
    local _, new = row(panel().bufid, "new.txt")
    assert.truthy(a:find("✓ a.go", 1, true))
    assert.truthy(a:find("+2 −1", 1, true))
    assert.truthy(new:find("○ new.txt", 1, true))
    eq(" new  +3 −0", new:sub(-#" new  +3 −0"))
    eq(width - 1, vim.api.nvim_strwidth(new))
    assert.falsy(text():find(" M ", 1, true))
  end)

  it("shows the first-review tip until a file is reviewed", function()
    open()
    assert.truthy(text():find("› Read a file, press r to mark it", 1, true))
    assert.truthy(text():gsub("\n%s*", " "):find("Tests and generated files are hidden.", 1, true))
    clubmate.set_reviewed("a.go", true, tab)
    assert.falsy(text():find("Read a file", 1, true))
  end)

  it("hides tests and generated by default", function()
    open()
    eq({ true, true, false, false, false }, {
      listed("a.go"), listed("new.txt"), listed("a_test.go"), listed("b_test.go"), listed("go.sum"),
    })
  end)

  it("toggles a filter from its checkbox", function()
    open()
    eq(true, click(panel().header_win, panel().header_buf, "☐ tests 2"))
    eq(true, listed("a_test.go"))
    assert.truthy(header():find("0 / 4 reviewed", 1, true))
    assert.truthy(header():find("☑ tests 2", 1, true))
    eq(true, click(panel().header_win, panel().header_buf, "☑ code"))
    eq(false, listed("a.go"))
    assert.truthy(header():find("0 / 2 reviewed", 1, true))
  end)

  it("draws the checkbox glyphs from the config", function()
    require("diffview").setup({ use_icons = false, file_panel = { checkbox = { on = "■", off = "□" } } })
    open()
    assert.truthy(header():find("Show ■ code □ tests 2 □ generated 1", 1, true))
  end)

  it("keeps the count and the folder when reviewed files are hidden and offers to show them", function()
    vim.fn.mkdir(repo .. "/d", "p")
    vim.fn.writefile({ "package d" }, repo .. "/d/x.go")
    open()
    clubmate.set_reviewed("a.go", true, tab)
    clubmate.set_reviewed("d/x.go", true, tab)
    assert.truthy(header():find("2 / 3 reviewed", 1, true))
    click(panel().header_win, panel().header_buf, "☑ reviewed")
    eq(false, listed("a.go"))
    eq(false, listed("x.go"))
    local _, folder = row(panel().bufid, "⌄ d")
    assert.truthy(folder and folder:find("1/1$"))
    assert.truthy(header():find("2 / 3 reviewed", 1, true))
    assert.truthy(text():find("2 reviewed files hidden · show", 1, true))
    eq(true, click(panel().winid, panel().bufid, "hidden · show", "show"))
    eq(true, listed("a.go"))
  end)

  it("keeps a hidden current file open", function()
    open()
    panel():toggle_filter("tests")
    clubmate.select("a_test.go", tab)
    wait_for(function()
      return view().cur_entry and view().cur_entry.path == "a_test.go"
    end)
    panel():toggle_filter("tests")
    eq("a_test.go", view().cur_entry.path)
    eq(false, vim.tbl_contains(vim.tbl_map(function(f)
      return f.path
    end, panel():ordered_file_list()), "a_test.go"))
    eq("code", panel():next_file().review_kind)
  end)

  it("says when every file is hidden", function()
    repo = vim.fn.tempname()
    vim.fn.mkdir(repo, "p")
    git(repo, "init", "-q")
    vim.fn.writefile({ "package x" }, repo .. "/x_test.go")
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "init")
    vim.fn.writefile({ "package x", "func TestX() {}" }, repo .. "/x_test.go")
    tab = clubmate.open({ cwd = repo, base = "HEAD" })
    wait_for(function()
      return view() and view().initialized and panel().header_buf ~= nil and header():find("0 / 0", 1, true) ~= nil
    end)
    assert.truthy(text():find("Every file is hidden by a filter", 1, true))
    eq(false, listed("x_test.go"))
  end)

  it("turns the header to done and the Send button primary once every file is reviewed", function()
    open()
    clubmate.set_meta(tab, { subtitle = "Claude", recipient = "Claude" })
    clubmate.set_reviewed("a.go", true, tab)
    clubmate.set_reviewed("new.txt", true, tab)
    assert.truthy(header():find("✓ All 2 files reviewed", 1, true))
    local marks = vim.api.nvim_buf_get_extmarks(panel().footer_buf, -1, 0, -1, { details = true })
    assert.truthy(vim.tbl_contains(marks, function(m)
      return m[4].hl_group == "DiffviewReviewButtonPrimary"
    end, { predicate = true }))
    clubmate.set_meta(tab, { subtitle = "Claude", recipient = "Claude", sent = 3 })
    assert.truthy(header():find("✓ 2/2 · 3 comments sent", 1, true))
  end)

  it("sends from the Send button", function()
    open()
    local sent = {}
    local rpcnotify = vim.rpcnotify
    vim.rpcnotify = function(_, _, payload)
      table.insert(sent, payload.kind)
    end
    clubmate.subscribe(7)
    local ok, err = pcall(click, panel().footer_win, panel().footer_buf, "Send review")
    vim.rpcnotify = rpcnotify
    assert(ok, err)
    assert.truthy(vim.tbl_contains(sent, "send"))
  end)

  it("moves on to the next file after staging a directory", function()
    vim.fn.mkdir(repo .. "/d", "p")
    vim.fn.writefile({ "package d" }, repo .. "/d/x.go")
    tab = clubmate.open({ cwd = repo })
    wait_for(function()
      return view() and view().initialized and view().cur_entry and panel():is_open()
    end)
    local dir
    panel().components.comp:deep_some(function(comp)
      if comp.name == "directory" and comp.context.name == "d" then
        dir = comp
        return true
      end
    end)
    vim.api.nvim_set_current_win(panel().winid)
    vim.api.nvim_win_set_cursor(panel().winid, { dir.lstart + 1, 0 })
    eq("d/x.go", panel().cur_file.path)
    require("diffview.actions").toggle_stage_entry()
    eq("a.go", panel().cur_file.path)
  end)

  it("draws the same panel without Send for a plain DiffviewOpen", function()
    local lib = require("diffview.lib")
    require("diffview").open({ "-C" .. repo, "HEAD" })
    local plain = lib.get_current_view()
    wait_for(function()
      return plain.cur_entry ~= nil and plain.cur_entry.opened and plain.panel.footer_buf ~= nil
    end)
    local foot = table.concat(lines(plain.panel.footer_buf), "\n")
    assert.truthy(table.concat(lines(plain.panel.header_buf), "\n"):find("Review " .. vim.fs.basename(repo), 1, true))
    assert.falsy(foot:find("Send", 1, true))
    assert.truthy(foot:find("Copy  ,re", 1, true))
    plain:close()
    lib.dispose_view(plain)
  end)

  helpers.nrev_it("lists open comments before resolved ones and jumps to one", function()
    require("nrev").setup({ bin = helpers.nrev_bin })
    local function add(line, kind, body)
      return vim.json.decode(helpers.nrev(repo, "add", "--file", "a.go", "--line-start", tostring(line),
        "--line-end", tostring(line), "--side", "new", "--rev", "WORKING", "--line-text", "x",
        "--type", kind, "--text", body)).id
    end
    local resolved = add(2, "suggestion", "align the names")
    add(3, "issue", "Workspace is set only by the Always allow path. Say so in a comment.")
    helpers.nrev(repo, "resolve", tostring(resolved))
    open()
    wait_for(function()
      return footer():find("Comments · 1 open", 1, true) ~= nil
    end)
    local i = row(panel().footer_buf, "● issue · a.go:3")
    local j = row(panel().footer_buf, "✓ suggestion · resolved · a.go:2")
    assert.truthy(i and j and i < j)
    assert.truthy(footer():find("Workspace is set only by the Al", 1, true))
    assert.truthy(footer():find("Send 1 comment ⌘↩", 1, true))
    assert.truthy(header():find("1 open comment", 1, true))
    clubmate.select("new.txt", tab)
    wait_for(function()
      return view().cur_entry.path == "new.txt" and view().cur_entry.opened
    end)
    click(panel().footer_win, panel().footer_buf, "● issue · a.go:3", "issue")
    wait_for(function()
      local win = vim.api.nvim_get_current_win()
      return view().cur_entry.path == "a.go" and win == view().cur_layout.b.id
        and vim.api.nvim_win_get_cursor(win)[1] == 3
    end)
  end)
end)
